/* Original topic lessons are authored in docs/knowledge; bundle supports file://. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'assets/data/learning-lab.js'),'utf8'),context);
const guides=Object.fromEntries(context.window.LEARNING_LAB.topics.map(topic=>{
  const source=`docs/knowledge/${topic.track}/${topic.id}.md`;
  return [topic.id,{source,markdown:fs.readFileSync(path.join(root,source),'utf8').replace(/\r\n/g,'\n')}];
}));
const content='// Generated by scripts/build_knowledge_guides.cjs. Edit docs/knowledge instead.\nwindow.LEARNING_KNOWLEDGE_GUIDES = '+JSON.stringify(guides,null,2)+';\n';
const target=path.join(root,'assets/data/knowledge-guides.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Knowledge guides are stale. Run node scripts/build_knowledge_guides.cjs');
  console.log('PASS: all 24 topic lessons match the offline bundle.');
}else{fs.writeFileSync(target,content);console.log('Built 24 detailed topic lessons.');}
