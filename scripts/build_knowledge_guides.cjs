/* Original topic lessons are authored in docs/knowledge; bundle supports file://. */
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'assets/data/learning-lab.js'),'utf8'),context);
const guides=Object.fromEntries(context.window.LEARNING_LAB.topics.map(topic=>{
  const source=`docs/knowledge/${topic.track}/${topic.id}.md`;
  return [topic.id,{source,markdown:fs.readFileSync(path.join(root,source),'utf8').replace(/\r\n/g,'\n')}];
}));
const packageSource='docs/knowledge/go/go-packages.md';
const packageMarkdown=fs.readFileSync(path.join(root,packageSource),'utf8').replace(/\r\n/g,'\n');
const packageMain=packageMarkdown.match(/### main\.go[^\n]*\n[\s\S]*?```go\n([\s\S]*?)\n```/);
if(!packageMain)throw Error('Go package tutorial must contain a complete main.go block.');
const toolMain=guides['go-tools'].markdown.match(/## 完整程序[^\n]*\n[\s\S]*?```go\n([\s\S]*?)\n```/);
if(!toolMain)throw Error('Go tool tutorial must contain a complete main.go block.');
const lessonGuides={
  'go-01':{...guides['go-tools'],starterCode:toolMain[1]},
  'go-06':{source:packageSource,markdown:packageMarkdown,starterCode:packageMain[1]}
};
const downloads=JSON.parse(fs.readFileSync(path.join(root,'assets/downloads/followup-manifest.json'),'utf8')).examples;
const followupGuides=Object.fromEntries(Array.from({length:12},(_,index)=>{
  const number=String(index).padStart(2,'0'),id='web-'+number;
  const source=`docs/followups/${id}.md`,examplePath=`exercises/web/followup-${number}`,download=`assets/downloads/web-followup-${number}.zip`;
  if(!fs.existsSync(path.join(root,examplePath,'README.md')) || !fs.existsSync(path.join(root,download)))throw Error(`${id}: complete example and source download required. Run python scripts/build_followup_examples.py`);
  const archive=downloads.find(item=>item.id===id);
  if(!archive || archive.examplePath!==examplePath || archive.download!==download)throw Error(`${id}: source download manifest does not match the lesson.`);
  return [id,{source,examplePath,archivePath:download,download:download+'?v='+archive.sha256.slice(0,12),sha256:archive.sha256,markdown:fs.readFileSync(path.join(root,source),'utf8').replace(/\r\n/g,'\n')}];
}));
const content='// Generated by scripts/build_knowledge_guides.cjs. Edit docs/knowledge or docs/followups instead.\nwindow.LEARNING_KNOWLEDGE_GUIDES = '+JSON.stringify(guides,null,2)+';\nwindow.LEARNING_LESSON_GUIDES = '+JSON.stringify(lessonGuides,null,2)+';\nwindow.LEARNING_FOLLOWUP_GUIDES = '+JSON.stringify(followupGuides,null,2)+';\n';
const target=path.join(root,'assets/data/knowledge-guides.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Knowledge guides are stale. Run node scripts/build_knowledge_guides.cjs');
  console.log('PASS: 24 knowledge topics and 12 complete stage lessons match the offline bundle.');
}else{fs.writeFileSync(target,content);console.log('Built 24 knowledge topics and 12 complete stage lessons.');}
