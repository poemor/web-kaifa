/* Course chapters are authored in docs/courses, with explicit prerequisites. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {marked}=require('../assets/vendor/marked.umd.js');
const root=path.resolve(__dirname,'..');
const catalogue=JSON.parse(fs.readFileSync(path.join(root,'docs/courses/catalog.json'),'utf8'));
const seen=new Set();
const lessons=catalogue.lessons.map((lesson,index)=>{
 assert(/^(web|go)-[a-z0-9-]+$/.test(lesson.id),'chapter ID');
 assert(!seen.has(lesson.id),'duplicate chapter');
 assert(catalogue.levels.some(level=>level.id===lesson.level),'chapter level');
 for(const prerequisite of lesson.prerequisites)assert(seen.has(prerequisite),lesson.id+' prerequisite must be taught first: '+prerequisite);
 const source=`docs/courses/${lesson.track}/${lesson.id}.md`;
 const markdown=fs.readFileSync(path.join(root,source),'utf8').replace(/\r\n/g,'\n');
 assert(markdown.startsWith('# '+lesson.title+'\n'),lesson.id+' title');
 assert(markdown.includes('## ')&&markdown.includes('```'),lesson.id+' explanation and example');
 // CJK punctuation beside a closing ** can leave the whole sentence unformatted.
 const html=marked.parse(markdown),prose=html.replace(/<pre\b[^>]*>[\s\S]*?<\/pre>/g,'').replace(/<code\b[^>]*>[\s\S]*?<\/code>/g,'');
 assert(html.includes('<strong>')&&!prose.includes('**'),lesson.id+' key conclusions must render in bold');
 if(lesson.example?.files)for(const content of Object.values(lesson.example.files))assert(markdown.includes(content.trim()),lesson.id+' sample must match source');
 seen.add(lesson.id);
 return {...lesson,number:catalogue.lessons.slice(0,index+1).filter(item=>item.track===lesson.track).length,source,markdown};
});
for(const ids of Object.values(catalogue.legacyLessons))for(const id of ids)assert(seen.has(id),'legacy lesson chapter '+id);
for(const ids of Object.values(catalogue.followups))for(const id of ids)assert(seen.has(id),'followup chapter '+id);
const data={...catalogue,lessons};
const output='// Generated by scripts/build_course_book.cjs. Edit docs/courses instead.\nwindow.COURSE_BOOK = '+JSON.stringify(data,null,2)+';\n';
const target=path.join(root,'assets/data/course-book.js');
if(process.argv.includes('--check')){
 assert.equal(fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n'),output,'course book bundle is stale');
 console.log('PASS: '+lessons.length+' sequenced course chapters match their sources.');
}else{fs.writeFileSync(target,output);console.log('Built '+lessons.length+' sequenced course chapters.');}
