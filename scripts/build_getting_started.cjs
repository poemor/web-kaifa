/* Single source: docs/tutorials. Generated script also works under file://. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const specs = [
  ['editor', '安装 VS Code', 'vscode.md', '下载编辑器、打开文件夹、保存文件与使用终端。'],
  ['web', 'Web 环境', 'web-environment.md', '运行第一个网页，检查保存、刷新与本地服务。'],
  ['go', 'Go 环境', 'go-environment.md', '看图选安装包，按系统安装与检查 PATH，再创建模块、运行和编译。'],
  ['ask', '学会问 AI', 'asking-ai.md', '用目标、环境、预期、实际、代码与尝试组织问题。']
];
const guides = specs.map(([id,title,file,summary]) => ({id,title,summary,source:'docs/tutorials/'+file,markdown:fs.readFileSync(path.join(root,'docs/tutorials',file),'utf8').replace(/\r\n/g,'\n')}));
const output = '// Generated by scripts/build_getting_started.cjs. Edit docs/tutorials instead.\nwindow.GETTING_STARTED = '+JSON.stringify(guides,null,2)+';\n';
const target = path.join(root,'assets/data/getting-started.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n') !== output) throw Error('Getting-started bundle is stale. Run node scripts/build_getting_started.cjs');
  console.log('PASS: four tutorial sources match the offline bundle.');
} else { fs.writeFileSync(target,output); console.log('Built four getting-started guides.'); }
