/* Browser integration checks. Needs Playwright and a running static HTTP server. */
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const BASE = process.env.SITE_TEST_URL || 'http://127.0.0.1:8743/';
const KEY = 'web-kaifa-study-v1';
const qa = path.resolve(__dirname, '../.qa');
fs.mkdirSync(qa, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const navigate = async (hash, title) => {
    await page.evaluate(value => { location.hash = value; }, hash);
    await page.waitForFunction(value => document.querySelector('main h1')?.textContent === value, title);
  };
  await page.goto(BASE);
  await page.waitForSelector('main h1');
  const curriculum = await page.evaluate(() => window.LEARNING_CURRICULUM);
  const adaptations = await page.evaluate(() => window.LEARNING_ADAPTATIONS);
  assert.equal(await page.locator('main h1').textContent(), '今天，写一点能运行的代码。');
  await page.screenshot({ path: path.join(qa, 'home-desktop.png'), fullPage: true });
  await page.locator('[data-home-track="go"]').click();
  assert.equal(await page.locator('.home-start .primary').getAttribute('href'), '#/lesson/go-01');
  assert.equal(await page.locator('[data-home-track="go"]').evaluate(el => el===document.activeElement), true);
  await page.locator('[data-home-track="web"]').click();
  assert.equal(await page.locator('.home-start .primary').getAttribute('href'), '#/lesson/web-01');
  await page.locator('#audience').selectOption('experienced');
  await navigate('/lesson/go-02', curriculum.go.lessons[1].title);
  await navigate('/home', '今天，写一点能运行的代码。');
  await page.locator('[data-home-track="web"]').click();
  assert.equal(await page.locator('.home-start .primary').getAttribute('href'), '#/lesson/web-01', 'direction overrides last lesson from another track');
  await page.locator('[data-home-track="go"]').click();
  assert.equal(await page.locator('.home-start .primary').getAttribute('href'), '#/lesson/go-02', 'return to real last lesson');
  await page.locator('#audience').selectOption('new');
  await navigate('/lesson/go-02', adaptations.goBeginner02.title);
  assert((await page.locator('.task-box').textContent()).includes('SumTo'));
  await navigate('/home', '今天，写一点能运行的代码。');
  for (const [track, course] of Object.entries(curriculum)) {
    for (const lesson of course.lessons) {
      const title = lesson.id === 'go-02' ? adaptations.goBeginner02.title : lesson.title;
      await navigate('/lesson/' + lesson.id, title);
      assert.equal(await page.locator('[data-check]').count(), lesson.checks.length);
      assert.equal(await page.locator('[data-answer]').count(), 3);
      if (track === 'go') assert.equal(await page.locator('[data-action="run-preview"]').count(), 0);
    }
  }
  for (let i = 0; i < curriculum.web.followups.length; i++) await navigate('/followup/web/' + i, curriculum.web.followups[i].title);
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).completed.length, KEY), 0, 'reading must not complete courses');
  await navigate('/lesson/web-01', curriculum.web.lessons[0].title);
  assert(await page.locator('#complete-lesson').isDisabled());
  const code = '<h1 id="proof">我亲手改了标题</h1><p>预览是真实的 HTML。</p>';
  await page.locator('[data-lesson-tab="code"]').click();
  await page.locator('#lesson-code').fill(code);
  await page.locator('[data-action="run-preview"]').click();
  await page.frameLocator('#code-preview').locator('#proof').waitFor();
  assert.equal(await page.frameLocator('#code-preview').locator('#proof').textContent(), '我亲手改了标题');
  await page.locator('[data-lesson-tab="review"]').click();
  await page.locator('#lesson-note').fill('我改了标题并刷新，输出和预期一致。');
  for (const input of await page.locator('[data-check]').all()) await input.check();
  assert(await page.locator('#complete-lesson').isDisabled(), 'checks alone are not completion');
  await page.locator(`[data-answer="${curriculum.web.lessons[0].quiz.answer}"]`).click();
  assert(await page.locator('#complete-lesson').isEnabled());
  await page.locator('#complete-lesson').click();
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).completed.join(','), KEY), 'web-01');
  assert.equal(await page.locator('#course-outline [aria-current="page"] .outline-done').count(), 1);
  await page.locator('[data-check="0"]').uncheck();
  assert.equal(await page.locator('#course-outline [aria-current="page"] .outline-done').count(), 0);
  assert.equal(await page.locator('.lesson-header .lesson-meta > span:last-child').textContent(), '待练习');
  await page.locator('[data-check="0"]').check();
  await page.locator('#complete-lesson').click();
  await page.reload(); await page.waitForSelector('#lesson-note', { state: 'attached' });
  assert.equal(await page.locator('#lesson-note').inputValue(), '我改了标题并刷新，输出和预期一致。');
  assert.equal(await page.locator('#lesson-code').inputValue(), code);
  assert.equal(await page.frameLocator('#code-preview').locator('#proof').count(), 0, 'saved edits must not run automatically');
  await navigate('/ai?lesson=web-01', '学到哪儿，问到哪儿');
  assert((await page.locator('#generated-prompt').textContent()).includes('第 1 课'));
  await page.locator('#ai-goal').fill('想让标题换成我的名字。');
  await page.locator('#ai-form summary').click();
  await page.locator('#ai-code').fill('<h1>我</h1>');
  await page.locator('#ai-error').fill('Web 旧报错');
  await page.locator('#ai-lesson').selectOption('go-01');
  const goPrompt = await page.locator('#generated-prompt').textContent();
  assert(goPrompt.includes('Go 第 1 课') && !goPrompt.includes('Web 旧报错') && !goPrompt.includes('<h1>我</h1>'));
  await page.locator('#ai-lesson').selectOption('web-01');
  assert.equal(await page.locator('#ai-error').inputValue(), 'Web 旧报错', 'per-course draft restored');
  await page.locator('#ai-level').selectOption('check');
  assert((await page.locator('#generated-prompt').textContent()).includes('检查下一步'));
  await page.locator('[data-filter="prompt"][data-value="go"]').click();
  assert.equal(await page.locator('.template-item').count(), 4);
  await navigate('/resources', '要查的时候，有地方查');
  await page.locator('[data-filter="resource"][data-value="web"]').click();
  assert.equal(await page.locator('.resource').count(), 10);
  await navigate('/progress', '留下自己做过的事');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('[data-action="export-json"]').click();
  const backupDownload = await downloadEvent;
  const backupPath = path.join(qa, 'roundtrip.json'); await backupDownload.saveAs(backupPath);
  const backup = JSON.parse(fs.readFileSync(backupPath, 'utf8'));
  assert(backup.state.completed.includes('web-01'));
  await page.locator('[data-action="reset-progress"]').click();
  await page.locator('[data-action="reset-progress"]').click();
  await page.locator('[data-action="undo"]').click();
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).completed[0], KEY), 'web-01', 'repeated clear must retain undo');
  await page.locator('[data-action="reset-progress"]').click();
  await page.locator('#import-progress').setInputFiles(backupPath);
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).completed.includes('web-01'), KEY);
  const saved = await page.evaluate(key => localStorage.getItem(key), KEY);
  await page.locator('#import-progress').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"type":"wrong","state":{}}') });
  await page.waitForFunction(() => document.querySelector('#import-status').textContent.includes('没有导入'));
  assert.equal(await page.evaluate(key => localStorage.getItem(key), KEY), saved);
  const oversized = JSON.parse(saved);
  for (const course of Object.values(curriculum)) for (const lesson of course.lessons) { oversized.notes[lesson.id] = '学'.repeat(10000); oversized.drafts[lesson.id] = 'x'.repeat(30000); }
  const largeBackup = Buffer.from(JSON.stringify({ type: 'web-kaifa-progress', version: 1, state: oversized }));
  assert(largeBackup.length > 2000000);
  await page.locator('#import-progress').setInputFiles({ name: 'large.json', mimeType: 'application/json', buffer: largeBackup });
  await page.waitForFunction(() => document.querySelector('#import-status').textContent.startsWith('已导入'));
  await page.evaluate(key => localStorage.setItem(key, JSON.stringify({ version: 1, lastLesson: 'toString', completed: [['web-01']], checks: {}, quiz: {}, notes: {} })), KEY);
  await page.reload(); await page.waitForSelector('main h1');
  assert.equal(await page.evaluate(key => JSON.parse(localStorage.getItem(key)).lastLesson, KEY), '');
  await navigate('/lesson/toString', '这里还没有这节课');
  await page.route('**/assets/data/curriculum.js*', async route => {
    const response = await route.fetch();
    const body = await response.text();
    await route.fulfill({ response, body: body + '\nwindow.LEARNING_CURRICULUM.web.lessons[0].sourceMarkdown = ' + JSON.stringify('[unsafe](<java\tscript:alert(1)>)\n\n<script>window.parent.attack=true</script>') + ';' });
  });
  await page.reload(); await page.waitForSelector('main h1');
  await navigate('/lesson/web-01', curriculum.web.lessons[0].title);
  assert.equal(await page.locator('#lesson-source a').count(), 0, 'dangerous URL must not be linked');
  assert.equal(await page.locator('#lesson-source script').count(), 0, 'source HTML must be escaped');
  let externalNavigations = 0;
  await page.route('https://example.invalid/**', async route => { externalNavigations++; await route.abort(); });
  await page.locator('[data-lesson-tab="code"]').click();
  await page.locator('#lesson-code').fill('<script>location.href="https://example.invalid/navigation-test"</script>');
  await page.locator('[data-action="run-preview"]').click();
  await page.waitForTimeout(300);
  assert.equal(externalNavigations, 0, 'preview navigation must not send external requests');
  await page.unroute('**/assets/data/curriculum.js*');
  await page.evaluate(key => localStorage.setItem(key, '{broken'), KEY);
  await page.reload(); await page.waitForSelector('main h1');
  assert.equal(await page.evaluate(key => localStorage.getItem(key + '-recovery'), KEY), '{broken');
  await navigate('/web', 'Web 从网页基础到完整应用');
  assert.equal(await page.evaluate(key => localStorage.getItem(key + '-recovery'), KEY), '{broken');
  await page.evaluate(() => localStorage.clear());
  await page.reload(); await page.waitForSelector('main h1');
  await navigate('/ai?mode=concept', '学到哪儿，问到哪儿');
  await page.screenshot({ path: path.join(qa, 'ai-desktop.png'), fullPage: true });
  for (const width of [320, 375, 414, 768]) {
    await page.setViewportSize({ width, height: 900 });
    for (const [hash, title] of [['/home', '今天，写一点能运行的代码。'], ['/ai', '学到哪儿，问到哪儿'], ['/lesson/web-05', curriculum.web.lessons[4].title], ['/progress', '留下自己做过的事']]) {
      await navigate(hash, title);
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
      assert(overflow <= 1, `${width}px ${hash}: horizontal overflow ${overflow}`);
    }
  }
  await page.setViewportSize({ width: 375, height: 900 });
  await navigate('/home', '今天，写一点能运行的代码。');
  await page.screenshot({ path: path.join(qa, 'home-mobile.png'), fullPage: true });
  await page.locator('#menu-toggle').click();
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'true');
  await page.locator('[data-nav="go"]').click();
  await page.waitForSelector('main .book-overview');
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'false');
  assert.deepEqual(errors, [], 'browser runtime errors');
  await browser.close();
  console.log('PASS: all 54 content routes, preview, honest completion, per-course AI context, filters, persistence, backup roundtrip, malformed/large inputs, recovery and 4 mobile widths.');
})().catch(error => { console.error(error); process.exit(1); });
